// CPU-side variants used to decompose the cost of the forward and inverse transformation.
using System.Security.Cryptography;
using ILGPU;
using ILGPU.Runtime;

public static class CpuVariants
{
    public const int BlockSize = 512 * 1024;   // as in the measured GPU series

    // (1) Original CPU baseline without a stream: per-container RandomNumberGenerator.Fill (HideByteToBuffer).
    public static void FormOriginalNoStream(AssocStego st, byte[] input, byte[] output)
    {
        int h = st.HiddenByteLength;
        for (int i = 0; i < input.Length; i++) st.HideByteToBuffer(input[i], output.AsSpan(i * h, h));
    }

    // (2) Same formula, filler generated by one RandomNumberGenerator.Fill call per 512 KB block.
    public static void FormBulkCsprng(AssocStego st, byte[] input, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = input.Length;
        int c = st.ContainerByteLength, h = st.HiddenByteLength;
        byte[] e = st.FlattenedEtalonsBytes, k = st.FlattenedKeysBytes;
        for (int start = from; start < to; start += BlockSize)
        {
            int n = Math.Min(BlockSize, to - start);
            RandomNumberGenerator.Fill(output.AsSpan(start * h, n * h));
            for (int i = start; i < start + n; i++)
            {
                int v = input[i];
                ApplyMask(output, i * h, v / 100, e, k, c);
                ApplyMask(output, i * h + c, (v % 100) / 10, e, k, c);
                ApplyMask(output, i * h + 2 * c, v % 10, e, k, c);
            }
        }
    }
    private static void ApplyMask(byte[] o, int off, int digit, byte[] e, byte[] k, int c)
    {
        int eo = digit * c;
        for (int j = 0; j < c; j++) { byte r = o[off + j]; o[off + j] = (byte)(r ^ ((r ^ e[eo + j]) & k[eo + j])); }
    }

    // (3) GPU filler function and GPU kernel logic, executed sequentially on the CPU (same block loop and seeds as GpuStegoEncryptor).
    public static void FormGpuFunction(AssocStego st, byte[] input, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = input.Length;
        var me = new ArrayView<byte>(st.FlattenedMaskedEtalonsBytes);
        var keys = new ArrayView<byte>(st.FlattenedKeysBytes);
        int c = st.ContainerByteLength, h = st.HiddenByteLength;
        for (int start = from; start < to; start += BlockSize)
        {
            int n = Math.Min(BlockSize, to - start);
            int blockSeed = RandomNumberGenerator.GetInt32(int.MinValue, int.MaxValue);
            var inV = new ArrayView<byte>(input, start, n);
            var outV = new ArrayView<byte>(output, (long)start * h, (long)n * h);
            for (int i = 0; i < n; i++) ThesisKernels.EncryptKernel(i, inV, outV, me, keys, c, start, blockSeed);
        }
    }

    // (4) Lower bound: masked etalons only, no filler generation (filler = 0).
    public static void FormZeroFiller(AssocStego st, byte[] input, byte[] output)
    {
        int c = st.ContainerByteLength, h = st.HiddenByteLength;
        byte[] e = st.FlattenedEtalonsBytes, k = st.FlattenedKeysBytes;
        for (int i = 0; i < input.Length; i++)
        {
            int v = input[i];
            ApplyMask(output, i * h, v / 100, e, k, c);
            ApplyMask(output, i * h + c, (v % 100) / 10, e, k, c);
            ApplyMask(output, i * h + 2 * c, v % 10, e, k, c);
        }
    }

    // Recognition variants ------------------------------------------------------------------------
    public static void RecOriginalNoStream(AssocStego st, byte[] hidden, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = output.Length;
        int h = st.HiddenByteLength;
        for (int i = from; i < to; i++) output[i] = st.DiscloseByteFromBuffer(hidden.AsSpan(i * h, h));
    }
    public static void RecGpuSearchLogic(AssocStego st, byte[] hidden, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = output.Length;
        var inV = new ArrayView<byte>(hidden); var outV = new ArrayView<byte>(output);
        var me = new ArrayView<byte>(st.FlattenedMaskedEtalonsBytes); var k = new ArrayView<byte>(st.FlattenedKeysBytes);
        int c = st.ContainerByteLength, ec = st.etalons.Length;
        for (int i = from; i < to; i++) ThesisKernels.DecryptKernel(i, inV, outV, me, k, c, 3, ec);
    }
    public static void RecBranchFree(AssocStego st, byte[] hidden, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = output.Length;
        var inV = new ArrayView<byte>(hidden); var outV = new ArrayView<byte>(output);
        var me = new ArrayView<byte>(st.FlattenedMaskedEtalonsBytes); var k = new ArrayView<byte>(st.FlattenedKeysBytes);
        int c = st.ContainerByteLength, ec = st.etalons.Length;
        for (int i = from; i < to; i++) NewKernels.DecryptBranchFreeKernel(i, inV, outV, me, k, c, 3, ec);
    }
    public static void RecTable(RecognitionTable tb, AssocStego st, byte[] hidden, byte[] output, int from = 0, int to = -1)
    {
        if (to < 0) to = output.Length;
        var inV = new ArrayView<byte>(hidden); var outV = new ArrayView<byte>(output);
        var pb = new ArrayView<int>(tb.PosByte); var pbit = new ArrayView<int>(tb.PosBit); var t = new ArrayView<byte>(tb.Table);
        int c = st.ContainerByteLength;
        for (int i = from; i < to; i++) NewKernels.DecryptTableKernel(i, inV, outV, pb, pbit, t, tb.M, c);
    }

    // Parallel wrappers (contiguous ranges, as proposed for the CPU-par baseline)
    public static void Par(int n, int range, Action<int, int> body) =>
        Parallel.ForEach(System.Collections.Concurrent.Partitioner.Create(0, n, range), r => body(r.Item1, r.Item2));
}
