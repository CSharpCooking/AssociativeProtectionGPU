# Extracts the classes EtalonFactory and AssocStego from the library listing (they do not depend on ILGPU)
# into Extracted.g.cs, so that the tests run the code of the listing itself.
import re, sys, pathlib
src = pathlib.Path(__file__).resolve().parent.parent / 'CpuGpuStego.cs'
s = src.read_text(encoding='utf-8')
def block(start, stop):
    i = s.index(start); j = s.index(stop, i); return s[i:j]
code = ('// generated by extract.py from library/CpuGpuStego.cs; do not edit\n#nullable enable\n'
        'using System.Security.Cryptography;\nusing System.Text;\n\n'
        + block('internal static class EtalonFactory', 'public class AssocStegoStream')
        + block('public class AssocStego\n', 'internal sealed class AcceleratorSession'))
pathlib.Path(__file__).resolve().parent.joinpath('Extracted.g.cs').write_text(code, encoding='utf-8')
print('extracted', len(code), 'chars')
